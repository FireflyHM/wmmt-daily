#!/usr/bin/env node
/*
 * Rebuilds public/data/titles.js from https://w.atwiki.jp/wmmt_title/.
 *
 *   node tools/build-titles.js              # download the 24 month pages
 *   node tools/build-titles.js <htmlDir>    # parse pages already saved in <htmlDir>
 *
 * Output shape:
 *   { en: { even: { "MM-DD": [t1..t6, bingo?] }, odd: {...} },
 *     ja: { even: {...}, odd: {...} } }
 * "en" is the wiki's overseas (外) row, "ja" the Japanese (日) row; both keep
 * the same column positions so titles line up between languages.
 */
const fs = require('fs');
const path = require('path');

const WIKI = 'https://w.atwiki.jp/wmmt_title/pages/';
const PAGES = Array.from({ length: 24 }, (_, i) => 13 + i); // pages/13.html … pages/36.html
const OUT = path.join(__dirname, '..', 'public', 'data', 'titles.js');

const decode = (s) => s
  .replace(/<br\s*\/?>/gi, ' ')
  .replace(/<[^>]+>/g, '')
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#0?39;/g, "'").replace(/&nbsp;/g, ' ')
  .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(+n))
  .replace(/\s+/g, ' ')
  .trim();

async function loadPages(dir) {
  if (dir) {
    return fs.readdirSync(dir).filter((f) => f.endsWith('.html'))
      .map((f) => fs.readFileSync(path.join(dir, f), 'utf8'));
  }
  const pages = [];
  for (const p of PAGES) {
    const res = await fetch(WIKI + p + '.html', { headers: { 'User-Agent': 'Mozilla/5.0 wmmt-daily' } });
    if (!res.ok) throw new Error(`pages/${p}.html: HTTP ${res.status}`);
    pages.push(await res.text());
    await new Promise((r) => setTimeout(r, 1000)); // be polite to the wiki
  }
  return pages;
}

function parsePage(html, out) {
  const title = decode((html.match(/<title>([\s\S]*?)<\/title>/) || [])[1] || '');
  const m = title.match(/(偶数|奇数)年?\s*(\d+)月/);
  if (!m) return console.warn('skipping page:', title);
  const parity = m[1] === '偶数' ? 'even' : 'odd';
  const month = +m[2];

  let date = null;
  for (const tr of html.match(/<tr[\s\S]*?<\/tr>/gi) || []) {
    let cells = (tr.match(/<t[dh][^>]*>[\s\S]*?<\/t[dh]>/gi) || []).map(decode);
    if (/^\d+\/\d+$/.test(cells[0] || '')) {
      date = cells[0];
      cells = cells.slice(1);
    } else if (cells[0] === '' && /^[日外]$/.test(cells[1] || '')) {
      cells = cells.slice(1); // second row of a date written without rowspan
    }
    const lang = { 外: 'en', 日: 'ja' }[cells[0]];
    if (!date || !lang) continue;

    const [mm, dd] = date.split('/').map(Number);
    if (mm !== month) console.warn(`date ${date} on the ${parity} ${month}月 page`);
    const titles = cells.slice(1, 8).map((x) => x.replace(/^【|】$/g, '').trim());
    while (titles.length && !titles[titles.length - 1]) titles.pop();
    out[lang][parity][String(mm).padStart(2, '0') + '-' + String(dd).padStart(2, '0')] = titles;
  }
}

(async () => {
  const out = { en: { even: {}, odd: {} }, ja: { even: {}, odd: {} } };
  for (const html of await loadPages(process.argv[2])) parsePage(html, out);

  const sorted = (o) => Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));
  for (const lang of ['en', 'ja']) {
    for (const parity of ['even', 'odd']) {
      out[lang][parity] = sorted(out[lang][parity]);
      console.log(lang, parity, Object.keys(out[lang][parity]).length, 'dates');
    }
  }

  fs.writeFileSync(OUT,
    '/* Daily titles from https://w.atwiki.jp/wmmt_title/ — generated by tools/build-titles.js.\n' +
    ' * { en|ja: { even|odd: { "MM-DD": [titles 1-6, 6RR bingo title when listed] } } } */\n' +
    '(function (root, data) {\n' +
    "  if (typeof module === 'object' && module.exports) module.exports = data;\n" +
    '  else root.WMMT_TITLES = data;\n' +
    "})(typeof self !== 'undefined' ? self : this, " + JSON.stringify(out) + ');\n');
  console.log('wrote', path.relative(process.cwd(), OUT));
})().catch((err) => {
  console.error(err);
  process.exit(1);
});
